// Folds raw Claude Code SDK messages (live stream + transcript history) into a
// conversation model the views can render. Pure data, no DOM.
//
// Conversation:
//   items:   ordered timeline (user | assistant | notice | boundary | result | output)
//   tools:   Map tool_use_id -> Tool (shared by assistant blocks, results, tasks, requests)
//   requests Map id -> pending permission / dialog / elicitation request
//
// Every mutation bumps item.v so the view can re-render only what changed.

export function createConversation(id) {
  return {
    id,
    items: [],
    byKey: new Map(),
    byMessageId: new Map(),
    tools: new Map(),
    drafts: new Map(),
    seen: new Set(),
    requests: new Map(),
    tasks: new Map(),
    hookEvents: [],
    state: "closed",
    statusText: null,
    todos: [],
    lastResult: null,
    suggestion: null,
    init: null,
    meta: {},
    contextUsage: null,
    rateLimit: null,
    turnStartedAt: null,
    lastUserUuid: null,
    version: 0,
    debug: [],
  };
}

let keyCounter = 0;
const nextKey = (prefix) => `${prefix}${++keyCounter}`;

function touch(conv, item) {
  item.v = (item.v || 0) + 1;
  conv.version += 1;
  return item;
}

function pushItem(conv, item) {
  item.key = item.key || nextKey(item.kind[0]);
  item.v = 1;
  conv.items.push(item);
  conv.byKey.set(item.key, item);
  conv.version += 1;
  return item;
}

// ---- helpers -----------------------------------------------------------------------
export function contentBlocks(content) {
  if (typeof content === "string") return content ? [{ type: "text", text: content }] : [];
  return Array.isArray(content) ? content : [];
}

export function toolResultText(content) {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return content == null ? "" : JSON.stringify(content);
  return content
    .map((part) => (part.type === "text" ? part.text : part.type === "image" ? "[image]" : JSON.stringify(part)))
    .join("\n");
}

const TAG = (name, text) => new RegExp(`<${name}>([\\s\\S]*?)</${name}>`).exec(text)?.[1];

/** Classify a user text coming from a transcript. */
function classifyUserText(text) {
  const trimmed = text.trim();
  if (!trimmed) return { kind: "skip" };
  if (/^<system-reminder>/.test(trimmed) && trimmed.endsWith("</system-reminder>")) return { kind: "skip" };
  const commandName = TAG("command-name", trimmed);
  if (commandName) {
    const args = (TAG("command-args", trimmed) || "").trim();
    return { kind: "command", name: commandName.trim(), args: args === "null" ? "" : args };
  }
  const stdout = TAG("local-command-stdout", trimmed);
  if (stdout !== undefined) return { kind: "output", text: stdout.trim() };
  const stderr = TAG("local-command-stderr", trimmed);
  if (stderr !== undefined) return { kind: "output", text: stderr.trim(), error: true };
  if (/^\[Request interrupted by user/.test(trimmed)) return { kind: "notice", text: trimmed.replace(/^\[|\]$/g, ""), level: "info", subtype: "interrupt" };
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(trimmed)) return { kind: "skip" };
  if (/^<(task-notification|bash-input|bash-stdout|bash-stderr)/.test(trimmed)) return { kind: "skip" };
  return { kind: "text", text };
}

export function getTool(conv, id, seed) {
  let tool = conv.tools.get(id);
  if (!tool) {
    tool = { id, name: "", input: null, status: "pending", result: null, children: [], v: 0, ...seed };
    conv.tools.set(id, tool);
  } else if (seed) {
    Object.assign(tool, seed);
  }
  return tool;
}

function touchTool(conv, tool) {
  tool.v += 1;
  conv.version += 1;
  const owner = tool.owner && conv.byKey.get(tool.owner);
  if (owner) touch(conv, owner);
}

// ---- assistant blocks --------------------------------------------------------------
function assistantItemFor(conv, messageId, seed) {
  let item = conv.byMessageId.get(messageId);
  if (!item) {
    item = pushItem(conv, { kind: "assistant", messageId, blocks: [], uuids: new Set(), streaming: false, ...seed });
    conv.byMessageId.set(messageId, item);
  }
  return item;
}

function applyFinalBlock(conv, item, block, parentToolUseId) {
  if (block.type === "tool_use" || block.type === "server_tool_use" || block.type === "mcp_tool_use") {
    const tool = getTool(conv, block.id, { name: block.name, input: block.input, server: block.server_name, owner: item.key });
    if (tool.status === "pending" || tool.status === "streaming") tool.status = "running";
    tool.startedAt ??= Date.now();
    tool.parentToolUseId = parentToolUseId || null;
    if (block.name === "TodoWrite" && Array.isArray(block.input?.todos)) conv.todos = block.input.todos;
    const existing = item.blocks.find((entry) => entry.type === "tool" && entry.toolUseId === block.id);
    if (!existing) item.blocks.push({ type: "tool", toolUseId: block.id });
    touchTool(conv, tool);
    return;
  }
  if (block.type === "text" || block.type === "thinking" || block.type === "redacted_thinking") {
    const type = block.type === "redacted_thinking" ? "thinking" : block.type;
    const text = block.type === "text" ? block.text : block.thinking || "";
    // Replace the matching streamed draft block (Nth block of this type) when present.
    item.finalCounts ??= { text: 0, thinking: 0 };
    const nth = item.finalCounts[type]++;
    const candidates = item.blocks.filter((entry) => entry.type === type);
    const target = candidates[nth];
    if (target) {
      target.text = text;
      target.streaming = false;
      target.redacted = block.type === "redacted_thinking";
    } else {
      item.blocks.push({ type, text, streaming: false, redacted: block.type === "redacted_thinking" });
    }
    return;
  }
  if (block.type === "web_search_tool_result" || block.type === "web_fetch_tool_result" || /_tool_result$/.test(block.type)) {
    const tool = conv.tools.get(block.tool_use_id);
    if (tool) {
      tool.result = { content: block.content, isError: false, structured: block.content };
      tool.status = "done";
      tool.endedAt ??= Date.now();
      touchTool(conv, tool);
    }
    return;
  }
  item.blocks.push({ type: "other", raw: block });
}

function applyAssistant(conv, msg) {
  const message = msg.message || {};
  const uuid = msg.uuid;
  if (uuid && conv.seen.has(uuid)) return;
  if (uuid) conv.seen.add(uuid);
  const blocks = contentBlocks(message.content);
  if (msg.parent_tool_use_id) {
    // Sub-agent output: nest under its Agent/Task tool card.
    const parent = getTool(conv, msg.parent_tool_use_id);
    for (const block of blocks) {
      if (block.type === "tool_use") {
        const child = getTool(conv, block.id, { name: block.name, input: block.input, status: "running", parentToolUseId: msg.parent_tool_use_id });
        if (!parent.children.includes(child.id)) parent.children.push(child.id);
        touchTool(conv, child);
      } else if (block.type === "text" && block.text?.trim()) {
        parent.notes = [...(parent.notes || []), block.text];
      }
    }
    touchTool(conv, parent);
    return;
  }
  const messageId = message.id || uuid || nextKey("m");
  const item = assistantItemFor(conv, messageId, {});
  if (uuid) item.uuids.add(uuid);
  item.model = message.model || item.model;
  item.usage = message.usage || item.usage;
  item.stopReason = message.stop_reason ?? item.stopReason;
  item.error = msg.error || item.error;
  item.aborted = msg.aborted || item.aborted;
  item.at ??= msg.timestamp ? Date.parse(msg.timestamp) : Date.now();
  if (item.streaming && message.stop_reason) item.streaming = false;
  conv.drafts.delete(messageId);
  for (const block of blocks) applyFinalBlock(conv, item, block, msg.parent_tool_use_id);
  touch(conv, item);
}

// ---- user messages -----------------------------------------------------------------
function applyUser(conv, msg, { live }) {
  const uuid = msg.uuid;
  const content = contentBlocks(msg.message?.content);
  const parent = msg.parent_tool_use_id;
  // Tool results
  let hadResult = false;
  for (const block of content) {
    if (block.type !== "tool_result") continue;
    hadResult = true;
    const tool = getTool(conv, block.tool_use_id);
    tool.result = {
      content: block.content,
      text: toolResultText(block.content),
      isError: Boolean(block.is_error),
      structured: msg.tool_use_result ?? tool.result?.structured,
    };
    if (msg.tool_use_result !== undefined) tool.structured = msg.tool_use_result;
    tool.status = block.is_error ? (/permission|denied|doesn't want to proceed|rejected/i.test(tool.result.text) ? "denied" : "error") : "done";
    tool.endedAt = Date.now();
    touchTool(conv, tool);
  }
  if (hadResult && !content.some((block) => block.type === "text" && block.text?.trim())) return;
  if (parent) return; // sub-agent prompt echo
  if (uuid && conv.seen.has(uuid)) return;
  if (uuid) conv.seen.add(uuid);
  if (msg.isSynthetic) return;
  const images = content.filter((block) => block.type === "image").map((block) => ({ mediaType: block.source?.media_type, data: block.source?.data }));
  const text = content.filter((block) => block.type === "text").map((block) => block.text).join("\n");
  const cls = classifyUserText(text);
  if (cls.kind === "skip" && !images.length) return;
  if (cls.kind === "notice") {
    pushItem(conv, { kind: "notice", level: cls.level, text: cls.text, subtype: cls.subtype });
    return;
  }
  if (cls.kind === "output") {
    pushItem(conv, { kind: "output", text: cls.text, error: cls.error });
    return;
  }
  const item = pushItem(conv, {
    kind: "user",
    uuid,
    text: cls.kind === "command" ? "" : cls.kind === "text" ? cls.text : "",
    command: cls.kind === "command" ? { name: cls.name, args: cls.args } : null,
    images,
    at: msg.timestamp ? Date.parse(msg.timestamp) : Date.now(),
  });
  conv.lastUserUuid = uuid;
  return item;
}

// ---- streaming ---------------------------------------------------------------------
function applyStreamEvent(conv, msg) {
  if (msg.parent_tool_use_id) return;
  const event = msg.event || {};
  if (event.type === "message_start") {
    const message = event.message || {};
    const item = assistantItemFor(conv, message.id, {});
    item.streaming = true;
    item.model = message.model || item.model;
    item.at ??= Date.now();
    item.draftIndex = new Map(); // content index -> block
    conv.drafts.set(message.id, item);
    conv.turnStartedAt ??= Date.now();
    touch(conv, item);
    return;
  }
  const messageId = [...conv.drafts.keys()].at(-1);
  const item = messageId && conv.drafts.get(messageId);
  if (!item) return;
  if (event.type === "content_block_start") {
    const block = event.content_block || {};
    let entry;
    if (block.type === "text") entry = { type: "text", text: block.text || "", streaming: true };
    else if (block.type === "thinking" || block.type === "redacted_thinking") entry = { type: "thinking", text: block.thinking || "", streaming: true };
    else if (block.type === "tool_use" || block.type === "server_tool_use" || block.type === "mcp_tool_use") {
      const tool = getTool(conv, block.id, { name: block.name, input: block.input && Object.keys(block.input).length ? block.input : null, status: "streaming", owner: item.key, partial: "" });
      entry = { type: "tool", toolUseId: block.id };
      tool.startedAt ??= Date.now();
    } else entry = { type: "other", raw: block };
    item.blocks.push(entry);
    item.draftIndex.set(event.index, entry);
    touch(conv, item);
    return;
  }
  if (event.type === "content_block_delta") {
    const entry = item.draftIndex?.get(event.index);
    if (!entry) return;
    const delta = event.delta || {};
    if (delta.type === "text_delta" && entry.type === "text") entry.text += delta.text;
    else if (delta.type === "thinking_delta" && entry.type === "thinking") entry.text += delta.thinking;
    else if (delta.type === "input_json_delta" && entry.type === "tool") {
      const tool = conv.tools.get(entry.toolUseId);
      tool.partial = (tool.partial || "") + (delta.partial_json || "");
      const parsed = tryParsePartial(tool.partial);
      if (parsed) tool.input = parsed;
      touchTool(conv, tool);
      return;
    }
    touch(conv, item);
    return;
  }
  if (event.type === "content_block_stop") {
    const entry = item.draftIndex?.get(event.index);
    if (entry && entry.type !== "tool") entry.streaming = false;
    if (entry?.type === "tool") {
      const tool = conv.tools.get(entry.toolUseId);
      const parsed = tool.partial ? tryParsePartial(tool.partial) : null;
      if (parsed) tool.input = parsed;
      if (tool.status === "streaming") tool.status = "running";
      touchTool(conv, tool);
    }
    touch(conv, item);
    return;
  }
  if (event.type === "message_delta") {
    if (event.delta?.stop_reason) item.stopReason = event.delta.stop_reason;
    if (event.usage) item.usage = { ...item.usage, ...event.usage };
    touch(conv, item);
    return;
  }
  if (event.type === "message_stop") {
    item.streaming = false;
    for (const entry of item.blocks) if (entry.type !== "tool") entry.streaming = false;
    touch(conv, item);
  }
}

function tryParsePartial(text) {
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch { /* try to close a truncated object */ }
  for (const suffix of ['"}', '"]}', "}", "]}", '"}]}', "}]}"]) {
    try {
      return JSON.parse(text + suffix);
    } catch { /* keep trying */ }
  }
  return null;
}

// ---- system ------------------------------------------------------------------------
function applySystem(conv, msg, { live }) {
  switch (msg.subtype) {
    case "init":
      conv.init = msg;
      conv.state = conv.state === "closed" ? "idle" : conv.state;
      break;
    case "status":
      conv.statusText = msg.status || null;
      if (msg.permissionMode) conv.meta = { ...conv.meta, permissionMode: msg.permissionMode };
      if (msg.compact_result === "failed") pushItem(conv, { kind: "notice", level: "error", text: msg.compact_error || "Compaction failed", subtype: "compact" });
      conv.version += 1;
      break;
    case "session_state_changed":
      conv.state = msg.state;
      if (msg.state === "running") conv.turnStartedAt ??= Date.now();
      if (msg.state === "idle") conv.turnStartedAt = null;
      conv.version += 1;
      break;
    case "compact_boundary":
      pushItem(conv, { kind: "boundary", text: "Conversation compacted", subtype: "compact", detail: msg.compact_metadata || null });
      break;
    case "api_retry":
      pushItem(conv, { kind: "notice", level: "warn", text: `API retry ${msg.attempt ?? ""}/${msg.max_retries ?? ""}`.trim(), detail: msg.error || msg.error_status, subtype: "retry" });
      break;
    case "local_command_output":
      pushItem(conv, { kind: "output", text: msg.content || msg.output || "" });
      break;
    case "task_started":
    case "task_progress":
    case "task_updated":
    case "task_notification": {
      const id = msg.task_id;
      if (!id) break;
      const task = conv.tasks.get(id) || { id, startedAt: Date.now() };
      Object.assign(task, {
        description: msg.description ?? task.description,
        summary: msg.summary ?? task.summary,
        status: msg.subtype === "task_notification" ? msg.status || "completed" : msg.patch?.status || msg.status || task.status || "running",
        toolUseId: msg.tool_use_id ?? task.toolUseId,
        taskType: msg.task_type ?? task.taskType,
        usage: msg.usage ?? task.usage,
        lastTool: msg.last_tool_name ?? task.lastTool,
        outputFile: msg.output_file ?? task.outputFile,
      });
      conv.tasks.set(id, task);
      if (task.toolUseId) {
        const tool = getTool(conv, task.toolUseId);
        tool.task = task;
        touchTool(conv, tool);
      }
      conv.version += 1;
      break;
    }
    case "hook_started":
    case "hook_progress":
    case "hook_response":
      conv.hookEvents.push({ ...msg, at: Date.now() });
      if (conv.hookEvents.length > 200) conv.hookEvents.shift();
      conv.version += 1;
      break;
    case "permission_denied":
      pushItem(conv, { kind: "notice", level: "warn", text: `Denied: ${msg.tool_name || ""}`.trim(), detail: msg.message || msg.reason, subtype: "denied" });
      break;
    case "conversation_reset":
      pushItem(conv, { kind: "boundary", text: "Conversation cleared", subtype: "clear" });
      break;
    case "informational":
    case "notification":
      pushItem(conv, { kind: "notice", level: msg.level === "error" ? "error" : msg.level === "warning" ? "warn" : "info", text: msg.message || msg.text || "", subtype: "info" });
      break;
    default:
      conv.debug.push({ type: "system", subtype: msg.subtype, at: Date.now() });
      if (conv.debug.length > 100) conv.debug.shift();
  }
}

function applyResult(conv, msg) {
  conv.drafts.clear();
  conv.state = conv.state === "requires_action" ? "idle" : conv.state === "running" ? "idle" : conv.state;
  conv.turnStartedAt = null;
  conv.statusText = null;
  conv.lastResult = msg;
  for (const tool of conv.tools.values()) {
    if (tool.status === "running" || tool.status === "streaming") {
      tool.status = msg.is_error && msg.subtype !== "success" ? "error" : tool.result ? "done" : "interrupted";
      touchTool(conv, tool);
    }
  }
  pushItem(conv, {
    kind: "result",
    isError: msg.is_error,
    subtype: msg.subtype,
    cost: msg.total_cost_usd,
    durationMs: msg.duration_ms,
    turns: msg.num_turns,
    usage: msg.usage,
    modelUsage: msg.modelUsage,
    denials: msg.permission_denials || [],
    text: msg.is_error ? msg.result || (msg.errors || []).join("\n") : "",
  });
}

// ---- entry point -------------------------------------------------------------------
/** msg: raw SDK message or synthetic wh_* message. live=false for history replay. */
export function applyMessage(conv, msg, { live = true } = {}) {
  switch (msg.type) {
    case "wh_user_message": {
      if (conv.seen.has(msg.uuid)) return;
      conv.seen.add(msg.uuid);
      pushItem(conv, { kind: "user", uuid: msg.uuid, text: msg.text, images: msg.images || [], at: msg.at, pending: true, priority: msg.priority });
      conv.lastUserUuid = msg.uuid;
      conv.turnStartedAt ??= Date.now();
      if (conv.state !== "requires_action") conv.state = "running";
      break;
    }
    case "user":
      applyUser(conv, msg, { live });
      break;
    case "assistant":
      applyAssistant(conv, msg);
      break;
    case "stream_event":
      applyStreamEvent(conv, msg);
      break;
    case "system":
      if (msg.uuid && !["init", "status", "session_state_changed"].includes(msg.subtype)) {
        if (conv.seen.has(msg.uuid)) break;
        conv.seen.add(msg.uuid);
      }
      applySystem(conv, msg, { live });
      break;
    case "result":
      if (msg.uuid) {
        if (conv.seen.has(msg.uuid)) break;
        conv.seen.add(msg.uuid);
      }
      applyResult(conv, msg);
      break;
    case "tool_progress": {
      const tool = conv.tools.get(msg.tool_use_id);
      if (tool) {
        tool.progress = { elapsed: msg.elapsed_time_seconds, name: msg.tool_name };
        touchTool(conv, tool);
      }
      break;
    }
    case "tool_use_summary":
      for (const id of msg.preceding_tool_use_ids || []) {
        const tool = conv.tools.get(id);
        if (tool) { tool.summary = msg.summary; touchTool(conv, tool); }
      }
      break;
    case "prompt_suggestion":
      conv.suggestion = msg.suggestion || null;
      conv.version += 1;
      break;
    case "rate_limit_event":
      conv.rateLimit = msg.rate_limit_info || msg;
      conv.version += 1;
      break;
    case "wh_request": {
      const request = msg.request;
      conv.requests.set(request.id, request);
      conv.state = "requires_action";
      const tool = request.toolUseID && conv.tools.get(request.toolUseID);
      if (tool) { tool.awaiting = request.id; touchTool(conv, tool); }
      conv.version += 1;
      break;
    }
    case "wh_request_resolved": {
      const request = conv.requests.get(msg.id);
      conv.requests.delete(msg.id);
      const tool = request?.toolUseID && conv.tools.get(request.toolUseID);
      if (tool) {
        tool.awaiting = null;
        if (msg.answer?.behavior === "deny" || msg.cancelled) { tool.status = "denied"; tool.denyMessage = msg.answer?.message; }
        touchTool(conv, tool);
      }
      if (!conv.requests.size && conv.state === "requires_action") conv.state = "running";
      conv.version += 1;
      break;
    }
    case "wh_error":
      pushItem(conv, { kind: "notice", level: "error", text: msg.message, detail: (msg.stderr || []).join("\n"), subtype: msg.where });
      break;
    case "wh_closed":
      conv.state = "closed";
      conv.requests.clear();
      conv.drafts.clear();
      for (const tool of conv.tools.values()) if (tool.status === "running" || tool.status === "streaming") { tool.status = "interrupted"; touchTool(conv, tool); }
      conv.version += 1;
      break;
    case "command_lifecycle":
    default:
      break;
  }
}

/** Load a transcript (SessionMessage[]) then the live buffer on top of it. */
export function loadHistory(conv, history) {
  for (const entry of history) applyMessage(conv, entry, { live: false });
  // Anything still marked running in a transcript is stale.
  for (const tool of conv.tools.values()) {
    if ((tool.status === "running" || tool.status === "streaming" || tool.status === "pending") && !tool.result) {
      tool.status = "interrupted";
    }
  }
}

/** Find the most recent user item (for checkpoints / rewind). */
export function userItems(conv) {
  return conv.items.filter((item) => item.kind === "user" && item.uuid);
}

export function isBusy(conv) {
  return conv.state === "running" || conv.state === "requires_action" || conv.state === "starting";
}
